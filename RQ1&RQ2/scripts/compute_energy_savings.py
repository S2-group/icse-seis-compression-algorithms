#!/usr/bin/env python3

import argparse
import re
from pathlib import Path
from urllib.parse import unquote, urlparse

import pandas as pd


DEFAULT_GRID_RESULTS_CSV = "../data/grid_search_summary/grid_search_all_results_normalized.csv"
DEFAULT_ENRICHED_CSV = "../data/top_2500_depended_enriched.csv"
DEFAULT_OUTPUT_DIR = "../data/grid_search_energy_savings"

DEFAULT_WH_PER_MB = 0.05
DEFAULT_MB_BASE = 1024 * 1024


DOWNLOAD_COLUMNS = [
    "DownloadsLastWeek",
    "DownloadsLastMonth",
    "DownloadsLastYear",
]


ENERGY_COLUMNS = [
    "TransmissionEnergySavingLastWeekWh",
    "TransmissionEnergySavingLastMonthWh",
    "TransmissionEnergySavingLastYearWh",
]


SUMMARY_NUMERIC_COLUMNS = [
    "SavedMBVsOriginal",
    "SavingVsOriginalPercent",
    "TransmissionEnergySavingLastWeekWh",
    "TransmissionEnergySavingLastMonthWh",
    "TransmissionEnergySavingLastYearWh",
]


def sanitize_filename(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9._@+-]+", "_", value)


def sanitize_package_for_prefixed_filename(package_name: str) -> str:
    value = str(package_name).strip().replace("/", "__")
    return re.sub(r"[^A-Za-z0-9._@+-]+", "_", value)


def strip_known_suffix(filename: str) -> str:
    suffixes = [
        ".tar.xz",
        ".tar.zst",
        ".tar.br",
        ".tgz",
        ".tar.gz",
    ]

    for suffix in suffixes:
        if filename.endswith(suffix):
            return filename[: -len(suffix)]

    return filename


def tarball_filename_from_url(url: str) -> str:
    if not isinstance(url, str) or not url.strip():
        return ""

    path = urlparse(url).path
    filename = Path(unquote(path)).name

    if not filename:
        return ""

    filename = sanitize_filename(filename)

    if not filename.endswith(".tgz"):
        filename = f"{filename}.tgz"

    return filename


def package_key_from_row(row: pd.Series) -> str:
    if "PackageKey" in row and str(row["PackageKey"]).strip():
        return str(row["PackageKey"]).strip()

    package_name = str(row.get("PackageName", "")).strip()
    latest_version = str(row.get("LatestVersion", "")).strip()
    dist_tarball = str(row.get("DistTarball", "")).strip()

    safe_package = (
        sanitize_package_for_prefixed_filename(package_name)
        if package_name
        else ""
    )

    tarball_filename = tarball_filename_from_url(dist_tarball)
    tarball_key = strip_known_suffix(tarball_filename) if tarball_filename else ""

    if safe_package and tarball_key:
        return f"{safe_package}--{tarball_key}"

    if safe_package and latest_version:
        unscoped_name = package_name.split("/")[-1]
        return f"{safe_package}--{unscoped_name}-{latest_version}"

    if package_name:
        return package_name

    return ""


def read_csv(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"CSV not found: {path}")

    return pd.read_csv(path, keep_default_na=False)


def load_grid_results(path: Path) -> pd.DataFrame:
    df = read_csv(path)

    required = [
        "PackageKey",
        "Algorithm",
        "Parameter",
        "CompressedBytes",
    ]

    missing = [column for column in required if column not in df.columns]
    if missing:
        raise ValueError(f"Grid results CSV is missing columns: {missing}")

    df = df.copy()

    df["PackageKey"] = df["PackageKey"].astype(str).str.strip()
    df["CompressedBytes"] = pd.to_numeric(df["CompressedBytes"], errors="coerce")

    if "OriginalBytes" in df.columns:
        df["OriginalBytes"] = pd.to_numeric(df["OriginalBytes"], errors="coerce")
    else:
        raise ValueError(
            "Grid results CSV must contain OriginalBytes. "
            "Use the normalized CSV generated by compare_grid_search.py."
        )

    if "Status" in df.columns:
        df = df[df["Status"] == "success"].copy()

    if "CompressedMB" not in df.columns:
        df["CompressedMB"] = df["CompressedBytes"] / DEFAULT_MB_BASE
    else:
        df["CompressedMB"] = pd.to_numeric(df["CompressedMB"], errors="coerce")

    if "OriginalMB" not in df.columns:
        df["OriginalMB"] = df["OriginalBytes"] / DEFAULT_MB_BASE
    else:
        df["OriginalMB"] = pd.to_numeric(df["OriginalMB"], errors="coerce")

    if "SpecialMode" not in df.columns:
        df["SpecialMode"] = "standard"

    if "ConfigLabel" not in df.columns:
        df["ConfigLabel"] = df["Parameter"].astype(str)

    if "ParameterOrdinal" not in df.columns:
        df["ParameterOrdinal"] = pd.NA

    df = df.dropna(subset=["PackageKey", "OriginalBytes", "CompressedBytes"])
    df = df[df["PackageKey"] != ""]

    return df


def load_downloads(path: Path) -> pd.DataFrame:
    df = read_csv(path)

    if "PackageKey" not in df.columns:
        df = df.copy()
        df["PackageKey"] = df.apply(package_key_from_row, axis=1)

    required = ["PackageKey"] + DOWNLOAD_COLUMNS
    missing = [column for column in required if column not in df.columns]

    if missing:
        raise ValueError(f"Downloads/enriched CSV is missing columns: {missing}")

    keep_columns = ["PackageKey"]

    if "PackageName" in df.columns:
        keep_columns.append("PackageName")

    keep_columns.extend(DOWNLOAD_COLUMNS)

    df = df[keep_columns].copy()

    df["PackageKey"] = df["PackageKey"].astype(str).str.strip()

    for column in DOWNLOAD_COLUMNS:
        df[column] = pd.to_numeric(df[column], errors="coerce").fillna(0)

    df = df[df["PackageKey"] != ""]
    df = df.drop_duplicates(subset=["PackageKey"], keep="first")

    return df


def add_energy_savings(
    grid: pd.DataFrame,
    downloads: pd.DataFrame,
    wh_per_mb: float,
    mb_base: float,
) -> pd.DataFrame:
    df = grid.merge(
        downloads,
        on="PackageKey",
        how="left",
        validate="many_to_one",
        suffixes=("", "_Downloads"),
    )

    for column in DOWNLOAD_COLUMNS:
        df[column] = pd.to_numeric(df[column], errors="coerce").fillna(0)

    df["SavedBytesVsOriginal"] = df["OriginalBytes"] - df["CompressedBytes"]
    df["SavedMBVsOriginal"] = df["SavedBytesVsOriginal"] / mb_base

    df["SavingVsOriginalPercent"] = (
        1 - (df["CompressedBytes"] / df["OriginalBytes"])
    ) * 100

    df["TransmissionEnergySavingLastWeekWh"] = (
        df["SavedMBVsOriginal"] * df["DownloadsLastWeek"] * wh_per_mb
    )
    df["TransmissionEnergySavingLastMonthWh"] = (
        df["SavedMBVsOriginal"] * df["DownloadsLastMonth"] * wh_per_mb
    )
    df["TransmissionEnergySavingLastYearWh"] = (
        df["SavedMBVsOriginal"] * df["DownloadsLastYear"] * wh_per_mb
    )

    df["TransmissionEnergySavingLastWeekKWh"] = (
        df["TransmissionEnergySavingLastWeekWh"] / 1000
    )
    df["TransmissionEnergySavingLastMonthKWh"] = (
        df["TransmissionEnergySavingLastMonthWh"] / 1000
    )
    df["TransmissionEnergySavingLastYearKWh"] = (
        df["TransmissionEnergySavingLastYearWh"] / 1000
    )

    df["HasTransmissionEnergySaving"] = df["SavedBytesVsOriginal"] > 0

    return df


def descriptive_stats(series: pd.Series) -> dict:
    s = pd.to_numeric(series, errors="coerce").dropna()

    if s.empty:
        return {
            "Count": 0,
            "Min": pd.NA,
            "Q1": pd.NA,
            "Median": pd.NA,
            "Q3": pd.NA,
            "Max": pd.NA,
            "Mean": pd.NA,
            "StdDev": pd.NA,
            "IQR": pd.NA,
            "Sum": pd.NA,
        }

    q1 = s.quantile(0.25)
    median = s.quantile(0.50)
    q3 = s.quantile(0.75)

    return {
        "Count": int(s.count()),
        "Min": s.min(),
        "Q1": q1,
        "Median": median,
        "Q3": q3,
        "Max": s.max(),
        "Mean": s.mean(),
        "StdDev": s.std(),
        "IQR": q3 - q1,
        "Sum": s.sum(),
    }


def summarize_by_config(df: pd.DataFrame) -> pd.DataFrame:
    group_cols = [
        "Algorithm",
        "Parameter",
        "SpecialMode",
        "ConfigLabel",
    ]

    if "ParameterOrdinal" in df.columns:
        group_cols.append("ParameterOrdinal")

    rows = []

    for keys, group in df.groupby(group_cols, dropna=False):
        if "ParameterOrdinal" in group_cols:
            algorithm, parameter, special_mode, config_label, parameter_ordinal = keys
        else:
            algorithm, parameter, special_mode, config_label = keys
            parameter_ordinal = pd.NA

        row = {
            "Algorithm": algorithm,
            "Parameter": parameter,
            "SpecialMode": special_mode,
            "ConfigLabel": config_label,
            "ParameterOrdinal": parameter_ordinal,
            "NPackages": len(group),
            "NPackagesWithPositiveSaving": int(group["HasTransmissionEnergySaving"].sum()),
            "NPackagesWithNegativeSaving": int((group["SavedBytesVsOriginal"] < 0).sum()),
            "TotalSavedMBVsOriginal": group["SavedMBVsOriginal"].sum(),
            "MedianSavedMBVsOriginal": group["SavedMBVsOriginal"].median(),
            "MedianSavingVsOriginalPercent": group["SavingVsOriginalPercent"].median(),
            "Q3SavingVsOriginalPercent": group["SavingVsOriginalPercent"].quantile(0.75),
            "TotalEnergySavingLastWeekWh": group["TransmissionEnergySavingLastWeekWh"].sum(),
            "TotalEnergySavingLastMonthWh": group["TransmissionEnergySavingLastMonthWh"].sum(),
            "TotalEnergySavingLastYearWh": group["TransmissionEnergySavingLastYearWh"].sum(),
            "TotalEnergySavingLastWeekKWh": group["TransmissionEnergySavingLastWeekKWh"].sum(),
            "TotalEnergySavingLastMonthKWh": group["TransmissionEnergySavingLastMonthKWh"].sum(),
            "TotalEnergySavingLastYearKWh": group["TransmissionEnergySavingLastYearKWh"].sum(),
            "MedianEnergySavingLastWeekWh": group["TransmissionEnergySavingLastWeekWh"].median(),
            "MedianEnergySavingLastMonthWh": group["TransmissionEnergySavingLastMonthWh"].median(),
            "MedianEnergySavingLastYearWh": group["TransmissionEnergySavingLastYearWh"].median(),
        }

        rows.append(row)

    summary = pd.DataFrame(rows)

    if summary.empty:
        return summary

    return summary.sort_values(
        by=["Algorithm", "SpecialMode", "Parameter"],
        ascending=[True, True, True],
    )


def descriptive_stats_by_config(df: pd.DataFrame) -> pd.DataFrame:
    group_cols = [
        "Algorithm",
        "Parameter",
        "SpecialMode",
        "ConfigLabel",
    ]

    rows = []

    for keys, group in df.groupby(group_cols, dropna=False):
        algorithm, parameter, special_mode, config_label = keys

        for column in SUMMARY_NUMERIC_COLUMNS:
            if column not in group.columns:
                continue

            stats = descriptive_stats(group[column])

            row = {
                "Algorithm": algorithm,
                "Parameter": parameter,
                "SpecialMode": special_mode,
                "ConfigLabel": config_label,
                "Column": column,
            }
            row.update(stats)

            rows.append(row)

    result = pd.DataFrame(rows)

    if result.empty:
        return result

    return result.sort_values(
        by=["Algorithm", "SpecialMode", "Parameter", "Column"],
        ascending=[True, True, True, True],
    )


def print_summary(summary: pd.DataFrame) -> None:
    pd.set_option("display.max_columns", None)
    pd.set_option("display.width", 240)
    pd.set_option("display.float_format", "{:,.4f}".format)

    print("\nEnergy savings summary by grid-search config")
    print("=" * 140)

    if summary.empty:
        print("No summary available.")
        return

    print_columns = [
        "Algorithm",
        "Parameter",
        "SpecialMode",
        "ConfigLabel",
        "NPackages",
        "NPackagesWithPositiveSaving",
        "NPackagesWithNegativeSaving",
        "TotalSavedMBVsOriginal",
        "MedianSavingVsOriginalPercent",
        "TotalEnergySavingLastWeekWh",
        "TotalEnergySavingLastMonthWh",
        "TotalEnergySavingLastYearWh",
        "TotalEnergySavingLastYearKWh",
    ]

    available_columns = [c for c in print_columns if c in summary.columns]

    print(summary[available_columns].to_string(index=False))


def print_descriptive_stats(stats: pd.DataFrame) -> None:
    pd.set_option("display.max_columns", None)
    pd.set_option("display.width", 220)
    pd.set_option("display.float_format", "{:,.4f}".format)

    if stats.empty:
        print("\nNo descriptive statistics available.")
        return

    print("\nDescriptive statistics by config")
    print("=" * 140)

    for algorithm in stats["Algorithm"].drop_duplicates():
        print(f"\nAlgorithm: {algorithm}")
        print("-" * 140)

        alg_stats = stats[stats["Algorithm"] == algorithm]

        for config_label in alg_stats["ConfigLabel"].drop_duplicates():
            print(f"\nConfig: {config_label}")
            subset = alg_stats[alg_stats["ConfigLabel"] == config_label]

            print(
                subset[
                    [
                        "Column",
                        "Count",
                        "Min",
                        "Q1",
                        "Median",
                        "Q3",
                        "Max",
                        "Mean",
                        "StdDev",
                        "IQR",
                        "Sum",
                    ]
                ].to_string(index=False)
            )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=(
            "Compute transmission energy savings for grid-search compression results."
        )
    )
    parser.add_argument(
        "--grid-results-csv",
        default=DEFAULT_GRID_RESULTS_CSV,
        help=(
            "Normalized grid-search CSV generated by compare_grid_search.py. "
            f"Default: {DEFAULT_GRID_RESULTS_CSV}"
        ),
    )
    parser.add_argument(
        "--enriched-csv",
        default=DEFAULT_ENRICHED_CSV,
        help=(
            "CSV with downloads columns. Must contain PackageKey or enough metadata "
            f"to derive it. Default: {DEFAULT_ENRICHED_CSV}"
        ),
    )
    parser.add_argument(
        "--output-dir",
        default=DEFAULT_OUTPUT_DIR,
        help=f"Output directory. Default: {DEFAULT_OUTPUT_DIR}",
    )
    parser.add_argument(
        "--wh-per-mb",
        type=float,
        default=DEFAULT_WH_PER_MB,
        help=f"Energy cost in Wh per MB transmitted. Default: {DEFAULT_WH_PER_MB}",
    )
    parser.add_argument(
        "--mb-base",
        type=float,
        default=DEFAULT_MB_BASE,
        help=(
            "Bytes per MB used in conversion. "
            f"Default: {DEFAULT_MB_BASE}, i.e. MiB."
        ),
    )

    args = parser.parse_args()

    grid_results_csv = Path(args.grid_results_csv)
    enriched_csv = Path(args.enriched_csv)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    grid = load_grid_results(grid_results_csv)
    downloads = load_downloads(enriched_csv)

    results = add_energy_savings(
        grid=grid,
        downloads=downloads,
        wh_per_mb=args.wh_per_mb,
        mb_base=args.mb_base,
    )

    summary = summarize_by_config(results)
    stats = descriptive_stats_by_config(results)

    detailed_path = output_dir / "grid_search_energy_savings_detailed.csv"
    summary_path = output_dir / "grid_search_energy_savings_summary_by_config.csv"
    stats_path = output_dir / "grid_search_energy_savings_descriptive_stats.csv"

    results.to_csv(detailed_path, index=False)
    summary.to_csv(summary_path, index=False)
    stats.to_csv(stats_path, index=False)

    matched_downloads = results[DOWNLOAD_COLUMNS].sum(axis=1).gt(0).sum()

    print("\nInput")
    print("=" * 140)
    print(f"Grid results CSV: {grid_results_csv}")
    print(f"Enriched/downloads CSV: {enriched_csv}")
    print(f"Grid rows loaded: {len(grid)}")
    print(f"Download rows loaded: {len(downloads)}")
    print(f"Grid rows with at least one non-zero download count: {matched_downloads}/{len(results)}")
    print(f"Wh per MB: {args.wh_per_mb}")
    print(f"MB base: {args.mb_base}")

    print_summary(summary)
    print_descriptive_stats(stats)

    print("\nOutput")
    print("=" * 140)
    print(f"Detailed CSV: {detailed_path}")
    print(f"Summary CSV: {summary_path}")
    print(f"Descriptive stats CSV: {stats_path}")


if __name__ == "__main__":
    main()